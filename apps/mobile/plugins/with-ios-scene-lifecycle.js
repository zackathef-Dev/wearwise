const fs = require('fs');
const path = require('path');
const { IOSConfig, withAppDelegate, withDangerousMod, withInfoPlist, withXcodeProject } = require('expo/config-plugins');

/* iOS 27 refuses to launch a UIKit app built with its SDK unless the app adopts the scene
   life cycle (crash in _UIApplicationEvaluateRuntimeIssueForNoSceneLifecycleAdoption). Expo SDK 57's
   template still creates the window in the app delegate, so this moves window creation into a
   SceneDelegate and re-feeds scene events to the app delegate, where Expo's subscribers and
   RCTLinkingManager listen. Expo SDK 58 ships ExpoAppSceneDelegate — delete this plugin then. */

const WINDOW_BLOCK = `#if os(iOS) || os(tvOS)
    window = UIWindow(frame: UIScreen.main.bounds)
    factory.startReactNative(
      withModuleName: "main",
      in: window,
      launchOptions: launchOptions)
#endif`;
const WINDOW_MARKER = '// The window and React Native start in SceneDelegate (iOS scene life cycle).';

const SCENE_DELEGATE = `internal import Expo
import React
import UIKit

// Generated by plugins/with-ios-scene-lifecycle.js — edit the plugin, not this file.
class SceneDelegate: UIResponder, UIWindowSceneDelegate {
  var window: UIWindow?

  private var appDelegate: AppDelegate? { UIApplication.shared.delegate as? AppDelegate }

  func scene(
    _ scene: UIScene,
    willConnectTo session: UISceneSession,
    options connectionOptions: UIScene.ConnectionOptions
  ) {
    guard let windowScene = scene as? UIWindowScene,
      let appDelegate,
      let factory = appDelegate.reactNativeFactory
    else {
      fatalError("SceneDelegate: AppDelegate has no React Native factory to start.")
    }

    let window = UIWindow(windowScene: windowScene)
    self.window = window
    // Code that reads UIApplication.shared.delegate?.window still finds it.
    appDelegate.window = window

    // A cold-start link arrives in connectionOptions, not the app delegate's launch options,
    // and Linking.getInitialURL() only reads launch options — rebuild them.
    var launchOptions: [UIApplication.LaunchOptionsKey: Any] = [:]
    if let url = connectionOptions.urlContexts.first?.url {
      launchOptions[UIApplication.LaunchOptionsKey(rawValue: "UIApplicationLaunchOptionsURLKey")] = url
    }
    factory.startReactNative(
      withModuleName: "main",
      in: window,
      launchOptions: launchOptions.isEmpty ? nil : launchOptions)

    connectionOptions.urlContexts.forEach { open($0) }
    connectionOptions.userActivities.forEach { self.continueActivity($0) }
  }

  func sceneDidBecomeActive(_ scene: UIScene) {
    appDelegate?.applicationDidBecomeActive(UIApplication.shared)
  }

  func sceneWillResignActive(_ scene: UIScene) {
    appDelegate?.applicationWillResignActive(UIApplication.shared)
  }

  func sceneWillEnterForeground(_ scene: UIScene) {
    appDelegate?.applicationWillEnterForeground(UIApplication.shared)
  }

  func sceneDidEnterBackground(_ scene: UIScene) {
    appDelegate?.applicationDidEnterBackground(UIApplication.shared)
  }

  func scene(_ scene: UIScene, openURLContexts URLContexts: Set<UIOpenURLContext>) {
    URLContexts.forEach { open($0) }
  }

  func scene(_ scene: UIScene, continue userActivity: NSUserActivity) {
    continueActivity(userActivity)
  }

  private func open(_ context: UIOpenURLContext) {
    var options: [UIApplication.OpenURLOptionsKey: Any] = [.openInPlace: context.options.openInPlace]
    if let source = context.options.sourceApplication { options[.sourceApplication] = source }
    if let annotation = context.options.annotation { options[.annotation] = annotation }
    _ = appDelegate?.application(UIApplication.shared, open: context.url, options: options)
  }

  private func continueActivity(_ activity: NSUserActivity) {
    _ = appDelegate?.application(UIApplication.shared, continue: activity, restorationHandler: { _ in })
  }
}
`;

module.exports = function withIosSceneLifecycle(config) {
  config = withInfoPlist(config, (mod) => {
    mod.modResults.UIApplicationSceneManifest = {
      UIApplicationSupportsMultipleScenes: false,
      UISceneConfigurations: {
        UIWindowSceneSessionRoleApplication: [{
          UISceneConfigurationName: 'Default Configuration',
          UISceneDelegateClassName: '$(PRODUCT_MODULE_NAME).SceneDelegate',
        }],
      },
    };
    return mod;
  });
  config = withAppDelegate(config, (mod) => {
    const contents = mod.modResults.contents;
    if (contents.includes(WINDOW_MARKER)) return mod;
    // Fail the prebuild rather than ship an app that iOS 27 kills at launch.
    if (!contents.includes(WINDOW_BLOCK)) throw new Error('with-ios-scene-lifecycle: AppDelegate window setup not found — the Expo template changed; update the plugin.');
    mod.modResults.contents = contents.replace(WINDOW_BLOCK, `    ${WINDOW_MARKER}`);
    return mod;
  });
  config = withDangerousMod(config, ['ios', (mod) => {
    const projectName = IOSConfig.XcodeUtils.getProjectName(mod.modRequest.projectRoot);
    fs.writeFileSync(path.join(mod.modRequest.platformProjectRoot, projectName, 'SceneDelegate.swift'), SCENE_DELEGATE);
    return mod;
  }]);
  return withXcodeProject(config, (mod) => {
    const projectName = IOSConfig.XcodeUtils.getProjectName(mod.modRequest.projectRoot);
    const filepath = `${projectName}/SceneDelegate.swift`;
    if (!mod.modResults.hasFile(filepath)) {
      IOSConfig.XcodeUtils.addBuildSourceFileToGroup({ filepath, groupName: projectName, project: mod.modResults });
    }
    return mod;
  });
};
