/* The dashboard's security headers, in one place. They are deployed two ways — public/_headers
 * (Netlify, Cloudflare Pages) and vercel.json (Vercel) — and both are generated from here so
 * they can't drift apart.
 *
 * connect-src allows only the Supabase backend this site is built for (HTTPS + the Realtime
 * websocket), so injected script couldn't send data anywhere else. The backend comes from
 * VITE_SUPABASE_URL, read the way Vite reads it for a production build (.env.production.local,
 * .env.production, .env.local, .env, then the real environment). Moving to another project,
 * a custom domain or a self-hosted Supabase:
 *
 *   npm run deploy-config -w dashboard          # rewrites public/_headers and vercel.json
 *
 * then commit both files. `vite build` refuses to build a site whose headers would block its
 * own backend (see vite.config.ts). With no HTTPS backend configured the files get a
 * placeholder host, which is what the repository ships with.
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

export const PLACEHOLDER_BACKEND = 'https://your-project-ref.supabase.co';

/** The CSP and other headers for every page, for a backend URL like https://abc.supabase.co. */
export function pageHeaders(backendUrl) {
  const host = new URL(backendUrl).host;
  return {
    'Content-Security-Policy': [
      "default-src 'self'", "script-src 'self'", "style-src 'self' 'unsafe-inline'",
      "img-src 'self' data: blob:", "font-src 'self'", `connect-src 'self' https://${host} wss://${host}`,
      "worker-src 'self' blob:", "frame-ancestors 'none'", "base-uri 'self'", "form-action 'self'",
      "object-src 'none'", 'upgrade-insecure-requests',
    ].join('; '),
    'X-Content-Type-Options': 'nosniff',
    'X-Frame-Options': 'DENY',
    'Referrer-Policy': 'no-referrer',
    // serial=(self) is what lets Patch setup reach a patch over USB.
    'Permissions-Policy': 'serial=(self), usb=(), bluetooth=(), camera=(), microphone=(), geolocation=(), payment=()',
    'Cross-Origin-Opener-Policy': 'same-origin',
    'Strict-Transport-Security': 'max-age=63072000; includeSubDomains',
  };
}

const PATH_HEADERS = {
  '/assets/*': { 'Cache-Control': 'public, max-age=31536000, immutable' },
  '/firmware/*': { 'Cache-Control': 'no-cache' },
};

export function headersFile(backendUrl) {
  const block = (path, headers) => [path, ...Object.entries(headers).map(([k, v]) => `  ${k}: ${v}`)].join('\n');
  return [
    '# GENERATED by scripts/deploy-headers.mjs (npm run deploy-config -w dashboard). Do not edit by hand.',
    '# Security and caching headers for Netlify and Cloudflare Pages; vercel.json carries the same values.',
    '# connect-src allows only the Supabase backend this site is built for.',
    '',
    block('/*', pageHeaders(backendUrl)),
    '',
    ...Object.entries(PATH_HEADERS).flatMap(([path, headers]) => [block(path, headers), '']),
  ].join('\n');
}

export function vercelConfig(backendUrl) {
  const list = (headers) => Object.entries(headers).map(([key, value]) => ({ key, value }));
  return {
    $schema: 'https://openapi.vercel.sh/vercel.json',
    buildCommand: 'npm run build',
    outputDirectory: 'dist',
    rewrites: [{ source: '/(.*)', destination: '/index.html' }],
    headers: [
      { source: '/(.*)', headers: list(pageHeaders(backendUrl)) },
      ...Object.entries(PATH_HEADERS).map(([path, headers]) => ({ source: path.replace('/*', '/(.*)'), headers: list(headers) })),
    ],
  };
}

/** The backend a deployable build would use: an HTTPS VITE_SUPABASE_URL, else the placeholder. */
export function deployBackend(env) {
  const url = env.VITE_SUPABASE_URL;
  try { if (url && new URL(url).protocol === 'https:') return url; } catch { /* placeholder below */ }
  return PLACEHOLDER_BACKEND;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { loadEnv } = await import('vite');
  const root = fileURLToPath(new URL('..', import.meta.url));
  const backend = deployBackend(loadEnv('production', root, 'VITE_'));
  writeFileSync(new URL('../public/_headers', import.meta.url), headersFile(backend));
  writeFileSync(new URL('../vercel.json', import.meta.url), `${JSON.stringify(vercelConfig(backend), null, 2)}\n`);
  console.log(`public/_headers and vercel.json now allow ${new URL(backend).host}${backend === PLACEHOLDER_BACKEND ? ' (placeholder: no HTTPS VITE_SUPABASE_URL found)' : ''}.`);
}
