import type { ButtonHTMLAttributes, CSSProperties, ReactNode } from 'react';
import { Link } from 'react-router';
import { Icon } from './Icon';
import { bySignalOrder, signalMeta } from '../data/signals';
import { cssVarName } from '../theme/tokens';

/* Small building blocks in the design system's vocabulary (Button, Badge, Alert,
   states). Status is always written in words as well as colour. */

type Variant = 'primary' | 'secondary' | 'ghost' | 'danger';

interface ButtonProps extends ButtonHTMLAttributes<HTMLButtonElement> {
  variant?: Variant;
  size?: 'md' | 'sm';
  icon?: string;
  busy?: boolean;
}

export function Button({ variant = 'secondary', size = 'md', icon, busy, children, className, disabled, ...rest }: ButtonProps) {
  return (
    <button
      type="button"
      className={`btn btn-${variant}${size === 'sm' ? ' btn-sm' : ''}${className ? ` ${className}` : ''}`}
      disabled={disabled || busy}
      aria-busy={busy || undefined}
      {...rest}
    >
      {busy ? <span className="spinner" style={{ width: 14, height: 14 }} aria-hidden /> : icon ? <Icon name={icon} size={size === 'sm' ? 14 : 16} /> : null}
      {children}
    </button>
  );
}

export function ButtonLink({ to, variant = 'secondary', size = 'md', icon, children }: {
  to: string; variant?: Variant; size?: 'md' | 'sm'; icon?: string; children: ReactNode;
}) {
  return (
    <Link to={to} className={`btn btn-${variant}${size === 'sm' ? ' btn-sm' : ''}`}>
      {icon && <Icon name={icon} size={size === 'sm' ? 14 : 16} />}
      {children}
    </Link>
  );
}

export type Tone = 'neutral' | 'success' | 'warning' | 'error' | 'info' | 'teal' | 'outline';

export function Badge({ tone = 'neutral', icon, children, title }: { tone?: Tone; icon?: string; children: ReactNode; title?: string }) {
  return (
    <span className={`badge badge-${tone}`} title={title}>
      {icon && <Icon name={icon} size={12} />}
      {children}
    </span>
  );
}

/** A signal with its data colour as a dot beside the (text-coloured) name. */
export function SignalBadge({ type }: { type: number }) {
  const m = signalMeta(type);
  return (
    <span className="badge badge-outline" title={`${m.label} (${m.unit})`}>
      <span className="swatch" style={{ '--swatch': tokenVar(m.token) } as CSSProperties} aria-hidden />
      {m.short}
    </span>
  );
}

export function SignalBadges({ types, falls }: { types: number[]; falls?: boolean }) {
  const sorted = [...new Set(types)].sort(bySignalOrder);
  return (
    <span className="signals">
      {sorted.map((t) => <SignalBadge key={t} type={t} />)}
      {falls && <Badge tone="outline" icon="triangle-alert">Falls</Badge>}
      {!sorted.length && !falls && <span className="muted">—</span>}
    </span>
  );
}

/** design-token key → `var(--…)` for style props (wwDataEcg → var(--ww-data-ecg)). */
export const tokenVar = (token: string): string => `var(${cssVarName(token)})`;

export function SessionStatusBadge({ status }: { status: string }) {
  if (status === 'complete') return <Badge tone="success" icon="circle-check">Complete</Badge>;
  if (status === 'interrupted') return <Badge tone="warning" icon="triangle-alert">Interrupted</Badge>;
  if (status === 'discarded') return <Badge tone="neutral">Discarded</Badge>;
  return <Badge tone="neutral">{status || 'Unknown'}</Badge>;
}

export function SimulatedBadge() {
  return <Badge tone="info" icon="flask" title="Generated by the app's simulator, not measured by a device">Simulated</Badge>;
}

export function FallStatusBadge({ status }: { status: string }) {
  return status === 'emergency'
    ? <Badge tone="error" icon="triangle-alert" title="The alarm was not cancelled">Emergency</Badge>
    : <Badge tone="neutral" title="The wearer tapped “I’m OK”">Marked OK</Badge>;
}

export function Spinner({ label = 'Loading' }: { label?: string }) {
  return <span className="spinner" role="status" aria-label={label} />;
}

export function LoadingState({ label = 'Loading…' }: { label?: string }) {
  return (
    <div className="state compact" role="status">
      <span className="spinner" aria-hidden />
      <span>{label}</span>
    </div>
  );
}

export function EmptyState({ icon = 'info', title, children, action }: { icon?: string; title: string; children?: ReactNode; action?: ReactNode }) {
  return (
    <div className="state">
      <span className="icon-ring"><Icon name={icon} size={22} /></span>
      <h2>{title}</h2>
      {children && <p>{children}</p>}
      {action}
    </div>
  );
}

export function ErrorState({ title = 'Something went wrong', message, onRetry }: { title?: string; message: string; onRetry?: () => void }) {
  return (
    <div className="state error" role="alert">
      <span className="icon-ring"><Icon name="triangle-alert" size={22} /></span>
      <h2>{title}</h2>
      <p>{message}</p>
      {onRetry && <Button icon="refresh-cw" onClick={onRetry}>Try again</Button>}
    </div>
  );
}

export function Alert({ kind = 'info', title, children, onDismiss }: {
  kind?: 'info' | 'success' | 'warning' | 'error'; title?: string; children?: ReactNode; onDismiss?: () => void;
}) {
  const icon = kind === 'success' ? 'circle-check' : kind === 'info' ? 'info' : 'triangle-alert';
  return (
    <div className={`alert alert-${kind}`} role={kind === 'error' ? 'alert' : 'status'}>
      <Icon name={icon} size={16} />
      <div className="alert-body">
        {title && <strong>{title}</strong>}
        {children && <span>{children}</span>}
      </div>
      {onDismiss && (
        <button type="button" className="btn btn-ghost btn-icon alert-dismiss" onClick={onDismiss} aria-label="Dismiss">
          <Icon name="x" size={14} />
        </button>
      )}
    </div>
  );
}
