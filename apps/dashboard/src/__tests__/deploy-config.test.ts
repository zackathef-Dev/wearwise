/// <reference types="node" />
import { readFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import { deployBackend, headersFile, PLACEHOLDER_BACKEND, vercelConfig } from '../../scripts/deploy-headers.mjs';

/* The security headers live in public/_headers (Netlify, Cloudflare Pages) and
   vercel.json (Vercel), both generated by scripts/deploy-headers.mjs. They must say the
   same thing, or one host ships weaker ones. */

const root = new URL('../../', import.meta.url);
const committedHeaders = readFileSync(new URL('public/_headers', root), 'utf8');
const vercel = JSON.parse(readFileSync(new URL('vercel.json', root), 'utf8')) as {
  headers: { source: string; headers: { key: string; value: string }[] }[];
  rewrites: { source: string; destination: string }[];
};

function parseHeaders(text: string): Record<string, Record<string, string>> {
  const out: Record<string, Record<string, string>> = {};
  let path = '';
  for (const line of text.split('\n')) {
    if (!line.trim() || line.trimStart().startsWith('#')) continue;
    if (!line.startsWith(' ')) { path = line.trim(); out[path] = {}; continue; }
    const [k, ...v] = line.trim().split(': ');
    out[path]![k!] = v.join(': ');
  }
  return out;
}

const toVercelSource = (p: string) => p.replace('/*', '/(.*)');

describe('deploy config', () => {
  const netlify = parseHeaders(committedHeaders);

  it('sends the same headers on every host', () => {
    for (const [path, headers] of Object.entries(netlify)) {
      const v = vercel.headers.find((h) => h.source === toVercelSource(path));
      expect(v, `vercel.json has no block for ${path}`).toBeDefined();
      expect(Object.fromEntries(v!.headers.map((h) => [h.key, h.value]))).toEqual(headers);
    }
    expect(vercel.headers).toHaveLength(Object.keys(netlify).length);
  });

  it('locks the page down: CSP, framing, USB only for this site', () => {
    const all = netlify['/*']!;
    expect(all['Content-Security-Policy']).toContain("frame-ancestors 'none'");
    expect(all['Content-Security-Policy']).toContain("script-src 'self';");
    expect(all['Content-Security-Policy']).not.toContain('*.supabase.co');
    /* The site can only reach one backend: exactly one https host and its wss twin. */
    expect(all['Content-Security-Policy']).toMatch(/connect-src 'self' https:\/\/([a-z0-9.-]+(?::\d+)?) wss:\/\/\1;/);
    expect(all['Permissions-Policy']).toContain('serial=(self)');
    expect(all['X-Frame-Options']).toBe('DENY');
  });

  it('committed files are exactly what the generator writes (edit scripts/deploy-headers.mjs, not them)', () => {
    const host = /connect-src 'self' (https:\/\/[^ ]+) /.exec(netlify['/*']!['Content-Security-Policy']!)![1]!;
    expect(headersFile(host)).toBe(committedHeaders);
    expect(vercelConfig(host)).toEqual(vercel);
  });

  it('only an HTTPS backend reaches the deploy headers; anything else gets the placeholder', () => {
    expect(deployBackend({ VITE_SUPABASE_URL: 'https://abc.supabase.co' })).toBe('https://abc.supabase.co');
    expect(deployBackend({ VITE_SUPABASE_URL: 'https://supabase.example.org' })).toBe('https://supabase.example.org');
    for (const url of ['http://127.0.0.1:54321', '', undefined, 'nonsense']) {
      expect(deployBackend({ VITE_SUPABASE_URL: url })).toBe(PLACEHOLDER_BACKEND);
    }
    expect(headersFile('https://supabase.example.org')).toContain("connect-src 'self' https://supabase.example.org wss://supabase.example.org;");
  });

  it('falls back to index.html for app routes', () => {
    expect(readFileSync(new URL('public/_redirects', root), 'utf8')).toMatch(/^\/\*\s+\/index\.html\s+200$/m);
    expect(vercel.rewrites).toEqual([{ source: '/(.*)', destination: '/index.html' }]);
  });
});
